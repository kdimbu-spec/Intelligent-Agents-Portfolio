"""# Create Deduplication Agent

Some papers appear in multiple databases.
"""

def deduplicate_papers(
    papers
):

    unique = {}

    for paper in papers:

        key = paper.get(
            "title",
            ""
        ).lower()

        if key not in unique:

            unique[key] = paper

    return list(
        unique.values()
    )

