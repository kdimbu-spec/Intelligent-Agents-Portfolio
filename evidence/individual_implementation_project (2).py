import pandas as pd

def research_interface(question_text, limit_val, use_llm_val, email_val):
    journal_logs = []
    errors = []

    journal_logs.append(f"[Journal] Starting research on: \"{question_text}\" with limit {limit_val}")

    try:
        # 1. Plan tasks
        journal_logs.append("[Journal] Activating Planner Agent...")
        plan = planner_agent(question_text)
        tasks = plan.get("tasks", [])

        # 2. Retrieve papers
        journal_logs.append(f"[Journal] Retrieving papers for {len(tasks)} planned sub-queries...")
        raw_papers = []
        for task in tasks:
            retrieved = retrieve_papers(task["query"])
            raw_papers.extend(retrieved)

        # 3. Deduplicate
        journal_logs.append(f"[Journal] Deduplicating {len(raw_papers)} raw results...")
        unique_papers = deduplicate_papers(raw_papers)
        journal_logs.append(f"[Journal] Found {len(unique_papers)} unique papers.")

        # 4. Limit to requested max papers
        selected_papers = unique_papers[:int(limit_val)]

        # 5. Process / Summarize papers
        journal_logs.append(f"[Journal] Processing and evaluating top {len(selected_papers)} papers...")
        processed_list = []
        for paper in selected_papers:
            processed_paper = process_paper(paper, question_text)
            processed_list.append(processed_paper)

            # Save to Vector DB memory
            try:
                memory.store_paper(
                    title=processed_paper.get("title", ""),
                    summary=processed_paper.get("processed_summary", ""),
                    source=processed_paper.get("source", ""),
                    url=processed_paper.get("url", ""),
                    research_question=question_text
                )
            except Exception as mem_ex:
                errors.append(f"Memory write warning: {mem_ex}")

        # Rank by score
        processed_list.sort(key=lambda x: x.get("relevance_score", 0), reverse=True)

        # 6. Generate gaps analysis using top processed papers
        journal_logs.append("[Journal] Identifying research gaps and synthesizing literature...")
        gap_analysis = identify_research_gaps(processed_list)

        # 7. Formulate a structured Markdown report
        journal_logs.append("[Journal] Formulating final markdown report...")
        report_md = f"# Research Synthesis Report\n\n**Question:** {question_text}\n\n"
        for idx, paper in enumerate(processed_list[:5]):
            report_md += f"### {idx+1}. {paper.get('title', 'Untitled')}\n"
            report_md += f"* **Source:** {paper.get('source', 'Unknown')} | **Year:** {paper.get('year', 'N/A')} | **Score:** {paper.get('relevance_score', 0)} ({paper.get('score_reason', '')})\n"
            report_md += f"* **Quality:** {paper.get('evidence_quality', 'Unknown')}\n"
            report_md += f"* **Summary:**\n{paper.get('processed_summary', 'No summary available.')}\n\n"

        # Convert papers to DataFrame for output view
        df_rows = []
        for p in processed_list:
            df_rows.append({
                "Title": p.get("title", ""),
                "Year": p.get("year", ""),
                "Source": p.get("source", ""),
                "Relevance Score": p.get("relevance_score", 0),
                "Quality": p.get("evidence_quality", "")
            })
        df_output = pd.DataFrame(df_rows)

        journal_logs.append("[Journal] Task complete!")

        return (
            report_md,
            gap_analysis,
            "\n".join(journal_logs),
            "\n".join(errors) if errors else "No errors detected.",
            df_output
        )

    except Exception as e:
        journal_logs.append(f"[Journal] Execution failed with error: {str(e)}")
        return (
            "# Research Failure",
            "Unable to generate analysis.",
            "\n".join(journal_logs),
            f"Error during run: {str(e)}\n{str(errors)}",
            pd.DataFrame()
        )

