from collections import Counter
import re

def extract_keywords(text):

    words = re.findall(
        r"\b[a-zA-Z]{4,}\b",
        text.lower()
    )

    common = Counter(words)

    return [
        keyword
        for keyword, count
        in common.most_common(10)
    ]

