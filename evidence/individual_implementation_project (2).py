"""# Create Workflow Orchestrator

This controls the agents.
"""

def run_research(
    research_question,
    sources,
    max_cycles=1
):

    state = ResearchState(
        question=research_question
    )

    state.plan = planner_agent(
        research_question
    )

    all_papers = []

    tasks = state.plan["tasks"]

    for task in tasks:

        papers = retrieve_papers(
            task["query"]
        )

        all_papers.extend(
            papers
        )

    state.retrieved_papers = (
        deduplicate_papers(
            all_papers
        )
    )

    state.cycle = 1

    state.sufficient = (
        len(
            state.retrieved_papers
        ) > 0
    )

    return state

